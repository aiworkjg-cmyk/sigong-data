/**
 * 기사 화면에 개인정보를 덜 드러내기 위한 표시 규칙.
 *
 * 기사는 "어느 현장인지 알아볼 수 있을 만큼"만 보면 됩니다. 그 이상은 필요도
 * 없고, 현장에서 켜 두는 화면이라 옆에서 들여다보일 수 있습니다. 원본 값은
 * 서버에 그대로 있고 관리자 화면에서는 온전히 보이므로, 여기서 가리는 것은
 * 기사에게 보여 줄 때뿐입니다.
 */

/** "홍길동" → "홍길*", "김철" → "김*", "이" → "이". */
export function maskName(value?: string): string {
  const name = (value || '').trim();
  if (name.length <= 1) return name;
  return `${name.slice(0, -1)}*`;
}

/**
 * 주소에서 동·호수를 뺍니다.
 *
 * **지금은 쓰이지 않습니다.** 기사 화면은 주소를 전체로 보여 줍니다 —
 * 동호수가 없으면 같은 아파트의 다른 동을 구분할 수 없어, 목록에서 현장을
 * 고르는 일 자체가 되지 않았습니다. 이름 가리기(maskName)는 그대로입니다.
 *
 * 함수를 지우지 않고 남겨 둡니다. 어디까지 보여 줄지는 운영하며 다시 정할 수
 * 있는 값이고, 그때 규칙을 처음부터 쓰게 하고 싶지 않습니다.
 */
export function maskAddress(value?: string): string {
  return (value || '')
    .replace(/\([^)]*\)/g, ' ')
    // 101동 1502호 / 1904동902호 / 602-101 / 4301동30
    .replace(/\d+\s*동\s*\d*\s*호?/g, ' ')
    .replace(/\d+\s*호\b/g, ' ')
    .replace(/\b\d{3,4}-\d{2,4}\b/g, ' ')
    .replace(/\s+/g, ' ')
    .replace(/[,·]\s*$/, '')
    .trim();
}
